export type DictKey = keyof (typeof dict)["bn"];

export function t(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  let s: string = dict[lang][key] ?? dict.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

export function formatPrice(amount: number, lang: Lang): string {
  const n = new Intl.NumberFormat(lang === "bn" ? "bn-BD" : "en-US").format(amount);
  return `৳${n}`;
}

export function localizedAge(ageGroup: string, lang: Lang): string {
  if (!ageGroup) return "";
  if (lang === "en") return `${ageGroup} ${dict.en.years}`;
  const bnDigits: Record<string, string> = {
    "0": "০", "1": "১", "2": "২", "3": "৩", "4": "৪",
    "5": "৫", "6": "৬", "7": "৭", "8": "৮", "9": "৯",
  };
  const bn = ageGroup.replace(/\d/g, (d) => bnDigits[d]);
  return `${bn} ${dict.bn.years}`;
}
